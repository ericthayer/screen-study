import { useCallback, useEffect, useState } from 'react';
import type { ArticleDraft, Groundedness, PublishRecord } from '../../shared/types';
import { api } from '../api';

interface Props {
  caseStudyId: string;
}

export function DraftsPage({ caseStudyId }: Props) {
  const [drafts, setDrafts] = useState<ArticleDraft[]>([]);
  const [active, setActive] = useState<ArticleDraft | null>(null);
  const [publishRecords, setPublishRecords] = useState<PublishRecord[]>([]);
  const [groundedness, setGroundedness] = useState<Groundedness | null>(null);
  // Polite live region text for async status changes (NFR-A3).
  const [status, setStatus] = useState('');
  const [markdown, setMarkdown] = useState('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const refresh = useCallback(async () => {
    const { drafts } = await api.listDrafts(caseStudyId);
    setDrafts(drafts);
  }, [caseStudyId]);

  useEffect(() => {
    setActive(null);
    void refresh();
  }, [refresh]);

  const open = async (id: string) => {
    const { draft, publishRecords, groundedness } = await api.getDraft(id);
    setActive(draft);
    setMarkdown(draft.markdown);
    setPublishRecords(publishRecords);
    setGroundedness(groundedness);
  };

  const generate = async () => {
    setError(null);
    // Organization rubric (AC-ORG-05): confirm before drafting a flagged outline.
    const { outline } = await api.getOutline(caseStudyId);
    if (
      outline.review.needsReview &&
      !window.confirm(
        `This outline needs review:\n\n- ${outline.review.reasons.join('\n- ')}\n\nGenerate a draft anyway?`,
      )
    ) {
      return;
    }
    setBusy(true);
    setStatus('Generating draft…');
    try {
      const { job } = await api.generateDraft(caseStudyId, outline.review.needsReview);
      // Draft generation runs as a background job; poll until it completes.
      let current = job;
      while (current.status === 'pending' || current.status === 'running') {
        await new Promise((r) => setTimeout(r, 500));
        current = (await api.getJob(job.id)).job;
      }
      if (current.status !== 'done' || !current.draftId) {
        throw new Error(current.error ?? 'Draft generation failed');
      }
      await refresh();
      await open(current.draftId);
      setStatus('Draft generated.');
    } catch (e) {
      setStatus('');
      setError(e instanceof Error ? e.message : String(e));
    } finally {
      setBusy(false);
    }
  };

  const save = async () => {
    if (!active) return;
    const { draft } = await api.updateDraft(active.id, { markdown });
    await refresh();
    await open(draft.id);
    setStatus(`Saved as version ${draft.version}.`);
  };

  const publish = async () => {
    if (!active) return;
    setError(null);
    try {
      await api.publishDraft(active.id);
      await open(active.id);
      await refresh();
      setStatus('Published.');
    } catch (e) {
      setError(e instanceof Error ? e.message : String(e));
    }
  };

  const latestPublish = publishRecords.find((r) => r.status === 'published');
  const publishBlocked = groundedness !== null && !groundedness.grounded;

  return (
    <div>
      <div className="toolbar">
        <button className="primary" onClick={() => void generate()} disabled={busy}>
          {busy ? 'Generating…' : 'Generate draft'}
        </button>
        {drafts.map((d) => (
          <button
            key={d.id}
            className={d.id === active?.id ? 'active' : ''}
            onClick={() => void open(d.id)}
          >
            v{d.version} ({d.status})
          </button>
        ))}
      </div>

      <p role="status" aria-live="polite" className="muted">
        {status}
      </p>
      {error && (
        <p role="alert" className="error">
          {error}
        </p>
      )}

      {active && (
        <div className="panel">
          <h3>
            {active.title} — v{active.version}{' '}
            <span className="muted" style={{ fontSize: '0.8rem' }}>
              {active.provider ? `generated by ${active.provider}` : 'edited'}
            </span>
          </h3>
          {groundedness && (
            <div id="groundedness" className={groundedness.grounded ? 'muted' : 'gap'}>
              {groundedness.grounded
                ? `Grounded: references ${groundedness.referencedMedia} of ${groundedness.totalMedia} supporting media.`
                : 'Publishing is disabled until this draft is grounded in its media:'}
              {groundedness.issues.length > 0 && (
                <ul>
                  {groundedness.issues.map((issue, i) => (
                    <li key={i}>{issue}</li>
                  ))}
                </ul>
              )}
            </div>
          )}
          <textarea
            aria-label="Article Markdown"
            className="article-editor"
            value={markdown}
            onChange={(e) => setMarkdown(e.target.value)}
          />
          <div className="toolbar" style={{ marginTop: '1rem', marginBottom: 0 }}>
            <button className="primary" onClick={() => void save()}>
              Save as new version
            </button>
            <a href={`/api/drafts/${active.id}/export`} download className="button-link">
              Export Markdown
            </a>
            <button
              onClick={() => void publish()}
              disabled={publishBlocked}
              aria-describedby={groundedness ? 'groundedness' : undefined}
            >
              Publish
            </button>
            {latestPublish && (
              <button
                className="danger"
                onClick={() =>
                  void api
                    .unpublish(latestPublish.id)
                    .then(() => open(active.id))
                    .then(() => setStatus('Unpublished.'))
                }
              >
                Unpublish
              </button>
            )}
          </div>
          {publishRecords.length > 0 && (
            <div style={{ marginTop: '1rem' }}>
              <p className="muted">Publish history</p>
              {publishRecords.map((r) => (
                <p key={r.id} className="muted" style={{ fontSize: '0.8rem', margin: '0.2rem 0' }}>
                  {r.status} → {r.path ?? r.error ?? ''}{' '}
                  {r.publishedAt ? `at ${r.publishedAt}` : ''}
                </p>
              ))}
            </div>
          )}
        </div>
      )}
    </div>
  );
}
